#!/usr/bin/env bash
# Renders the Homebrew formula and the Scoop manifest for one release from
# its SHA256SUMS file.
#
# Usage: scripts/render-packaging.sh <version> <SHA256SUMS> <out-dir>
# Example: scripts/render-packaging.sh 0.1.0 dist/SHA256SUMS packaging
#
# Writes <out-dir>/homebrew/mockingbird.rb (for the RJ-s-Org/homebrew-tap
# repository, as Formula/mockingbird.rb) and <out-dir>/scoop/mockingbird.json.
# Exits 1 when SHA256SUMS lacks an archive the formula or manifest needs, 2 on
# bad usage.
set -euo pipefail

if [[ $# -ne 3 ]]; then
    echo "usage: $0 <version> <SHA256SUMS> <out-dir>" >&2
    exit 2
fi
VERSION=${1#v}
SUMS=$2
OUT=$3
REPO=https://github.com/RJ-s-Org/Mockingbird

sum() { # target extension
    local file="mockingbird-$VERSION-$1.$2" hash
    hash=$(awk -v f="$file" '{ name = $2; sub(/^\*/, "", name) } name == f { print $1 }' "$SUMS")
    [[ -n $hash ]] || { echo "render-packaging: $file is not in $SUMS" >&2; exit 1; }
    echo "$hash"
}

MAC_ARM=$(sum aarch64-apple-darwin tar.gz)
MAC_X64=$(sum x86_64-apple-darwin tar.gz)
LINUX_ARM=$(sum aarch64-unknown-linux-musl tar.gz)
LINUX_X64=$(sum x86_64-unknown-linux-musl tar.gz)
WIN_X64=$(sum x86_64-pc-windows-msvc zip)
BASE="$REPO/releases/download/v$VERSION"

mkdir -p "$OUT/homebrew" "$OUT/scoop"

cat > "$OUT/homebrew/mockingbird.rb" <<RUBY
# Generated by scripts/render-packaging.sh from the v$VERSION release; do not edit.
class Mockingbird < Formula
  desc "LLM-backed API mocks for every protocol, stateful, with a zero-edit proxy"
  homepage "$REPO"
  version "$VERSION"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    on_arm do
      url "$BASE/mockingbird-$VERSION-aarch64-apple-darwin.tar.gz"
      sha256 "$MAC_ARM"
    end
    on_intel do
      url "$BASE/mockingbird-$VERSION-x86_64-apple-darwin.tar.gz"
      sha256 "$MAC_X64"
    end
  end

  on_linux do
    on_arm do
      url "$BASE/mockingbird-$VERSION-aarch64-unknown-linux-musl.tar.gz"
      sha256 "$LINUX_ARM"
    end
    on_intel do
      url "$BASE/mockingbird-$VERSION-x86_64-unknown-linux-musl.tar.gz"
      sha256 "$LINUX_X64"
    end
  end

  def install
    bin.install "mockingbird"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/mockingbird --version")
  end
end
RUBY

cat > "$OUT/scoop/mockingbird.json" <<JSON
{
    "version": "$VERSION",
    "description": "LLM-backed API mocks for every protocol, stateful, with a zero-edit proxy",
    "homepage": "$REPO",
    "license": "MIT|Apache-2.0",
    "architecture": {
        "64bit": {
            "url": "$BASE/mockingbird-$VERSION-x86_64-pc-windows-msvc.zip",
            "hash": "$WIN_X64",
            "extract_dir": "mockingbird-$VERSION-x86_64-pc-windows-msvc"
        }
    },
    "bin": "mockingbird.exe",
    "checkver": {
        "github": "$REPO"
    },
    "autoupdate": {
        "architecture": {
            "64bit": {
                "url": "$REPO/releases/download/v\$version/mockingbird-\$version-x86_64-pc-windows-msvc.zip",
                "hash": {
                    "url": "\$url.sha256"
                },
                "extract_dir": "mockingbird-\$version-x86_64-pc-windows-msvc"
            }
        }
    }
}
JSON
echo "render-packaging: wrote $OUT/homebrew/mockingbird.rb and $OUT/scoop/mockingbird.json for v$VERSION"
