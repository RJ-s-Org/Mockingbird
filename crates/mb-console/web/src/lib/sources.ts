/** A response source's label and explanation. */
export interface SourceLabel {
  label: string;
  hint: string;
}

const NOT_GENERATED: SourceLabel = {
  label: "Not generated (rejected or failed before generation)",
  hint:
    "Requests answered without generating a body: rejected by validation, data-plane auth or limits, " +
    "unknown routes, or failures before generation.",
};

const SOURCES: Record<string, SourceLabel> = {
  llm: { label: "LLM", hint: "Generated by the LLM." },
  repaired: { label: "LLM (repaired)", hint: "Generated by the LLM, then repaired to match the schema." },
  fallback: {
    label: "Fallback",
    hint: "Generated without the LLM from the schema (offline, or the LLM failed or was over budget).",
  },
  // The server's `not_generated`, and the names older servers used for it.
  not_generated: NOT_GENERATED,
  none: NOT_GENERATED,
  rejected: NOT_GENERATED,
};

/** The label of a `mb_requests_total` `source` value; an unknown one is shown as is. */
export function sourceLabel(source: string): SourceLabel {
  return SOURCES[source.toLowerCase()] ?? { label: source, hint: source };
}
