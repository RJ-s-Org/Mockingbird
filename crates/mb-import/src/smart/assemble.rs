/// Version of every assembled draft document.
const DRAFT_VERSION: &str = "0.1.0-draft";
const DRAFT_DESCRIPTION: &str = "Draft generated by Mockingbird smart import";
const DEFAULT_CONTENT_TYPE: &str = "application/json";
const COMPONENTS_PREFIX: &str = "#/components/schemas/";
/// Longest accepted own operation id.
const MAX_ID_CHARS: usize = 64;

/// One problem found in a draft document.
#[derive(Serialize, Clone, Debug, PartialEq)]
pub struct DraftIssue {
    /// JSON pointer into the draft document.
    pub pointer: String,
    pub message: String,
}

impl DraftIssue {
    fn new(pointer: impl Into<String>, message: impl Into<String>) -> Self {
        Self {
            pointer: pointer.into(),
            message: message.into(),
        }
    }
}

/// What differs between the active version and a draft.
#[derive(Serialize, Clone, Debug, PartialEq, Default)]
pub struct BundleDiff {
    pub added: Vec<String>,
    pub removed: Vec<String>,
    pub changed: Vec<String>,
}

/// Whether `id` is `^[A-Za-z_][A-Za-z0-9_]{0,63}$`.
fn valid_id(id: &str) -> bool {
    let mut chars = id.chars();
    chars
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
        && id.len() <= MAX_ID_CHARS
}

/// The operation's own id when valid and unused, else
/// `<method>_<path slug>` with a numeric suffix on collision.
fn assign_id(op: &DraftOperation, used: &mut HashSet<String>) -> String {
    if let Some(own) = op.operation_id.as_deref()
        && valid_id(own)
        && !used.contains(own)
    {
        used.insert(own.to_string());
        return own.to_string();
    }
    let base = format!(
        "{}_{}",
        op.method.to_ascii_lowercase(),
        slug(&op.path).replace('-', "_")
    );
    let mut id = base.clone();
    let mut n = 2;
    while used.contains(&id) {
        id = format!("{base}_{n}");
        n += 1;
    }
    used.insert(id.clone());
    id
}

/// Names of the `{params}` of a path template, in order.
fn template_params(path: &str) -> Vec<&str> {
    path.split('/')
        .filter_map(|s| s.strip_prefix('{').and_then(|s| s.strip_suffix('}')))
        .collect()
}

fn location_str(location: &ParamLocation) -> &'static str {
    match location {
        ParamLocation::Path => "path",
        ParamLocation::Query => "query",
        ParamLocation::Header => "header",
    }
}

fn param_schema(param: &DraftParam) -> Value {
    if let Some(schema) = &param.schema {
        return schema.clone();
    }
    let samples: Vec<&str> = param.examples.iter().filter_map(Value::as_str).collect();
    if samples.is_empty() {
        json!({"type": "string"})
    } else {
        infer_scalar(&samples)
    }
}

fn param_object(param: &DraftParam) -> Value {
    let mut obj = Map::new();
    obj.insert("name".into(), json!(param.name));
    obj.insert("in".into(), json!(location_str(&param.location)));
    obj.insert(
        "required".into(),
        json!(param.required || param.location == ParamLocation::Path),
    );
    if let Some(d) = &param.description {
        obj.insert("description".into(), json!(d));
    }
    obj.insert("schema".into(), param_schema(param));
    if let Some(example) = param.examples.first() {
        obj.insert("example".into(), example.clone());
    }
    Value::Object(obj)
}

/// The parameters of `op`: the declared ones, except path parameters not in
/// the template, plus a string parameter for every undeclared `{name}`.
fn parameters(op: &DraftOperation, warnings: &mut Vec<DraftWarning>) -> Vec<Value> {
    let template = template_params(&op.path);
    let mut out: Vec<Value> = Vec::new();
    for name in &template {
        match op
            .parameters
            .iter()
            .find(|p| p.location == ParamLocation::Path && p.name == *name)
        {
            Some(param) => out.push(param_object(param)),
            None => {
                let target = op.target();
                warnings.push(
                    DraftWarning::new(
                        "missing_path_parameter",
                        format!(
                            "{target}: the path parameter {name} was not described; it was added as a string"
                        ),
                    )
                    .for_operation(target),
                );
                out.push(json!({
                    "name": name,
                    "in": "path",
                    "required": true,
                    "schema": {"type": "string"}
                }));
            }
        }
    }
    let mut seen: HashSet<(&'static str, &str)> = HashSet::new();
    for param in &op.parameters {
        if param.location == ParamLocation::Path {
            continue;
        }
        if seen.insert((location_str(&param.location), param.name.as_str())) {
            out.push(param_object(param));
        }
    }
    out
}

/// A media type object: the schema (inferred from the examples when
/// missing) and the first example.
fn media(schema: Option<&Value>, examples: &[Value]) -> Value {
    let mut obj = Map::new();
    let schema = match schema {
        Some(s) => Some(s.clone()),
        None if !examples.is_empty() => Some(infer_schema(examples)),
        None => None,
    };
    if let Some(schema) = schema {
        obj.insert("schema".into(), schema);
    }
    if let Some(example) = examples.first() {
        obj.insert("example".into(), example.clone());
    }
    Value::Object(obj)
}

fn request_body(body: &DraftBody) -> Value {
    let ct = if body.content_type.trim().is_empty() {
        DEFAULT_CONTENT_TYPE
    } else {
        body.content_type.as_str()
    };
    json!({"content": {ct: media(body.schema.as_ref(), &body.examples)}})
}

fn reason_phrase(status: u16) -> &'static str {
    match status {
        200 => "OK",
        201 => "Created",
        202 => "Accepted",
        204 => "No Content",
        301 => "Moved Permanently",
        302 => "Found",
        304 => "Not Modified",
        400 => "Bad Request",
        401 => "Unauthorized",
        403 => "Forbidden",
        404 => "Not Found",
        409 => "Conflict",
        422 => "Unprocessable Content",
        429 => "Too Many Requests",
        500 => "Internal Server Error",
        503 => "Service Unavailable",
        _ => "Response",
    }
}

fn response_object(response: &DraftResponse) -> Value {
    let mut obj = Map::new();
    let description = response
        .description
        .clone()
        .filter(|d| !d.trim().is_empty())
        .unwrap_or_else(|| reason_phrase(response.status).to_string());
    obj.insert("description".into(), json!(description));
    if response.content_type.is_some() || response.schema.is_some() || !response.examples.is_empty()
    {
        let ct = response
            .content_type
            .as_deref()
            .filter(|c| !c.trim().is_empty())
            .unwrap_or(DEFAULT_CONTENT_TYPE);
        obj.insert(
            "content".into(),
            json!({ct: media(response.schema.as_ref(), &response.examples)}),
        );
    }
    Value::Object(obj)
}

fn operation_object(op: &DraftOperation, id: &str, warnings: &mut Vec<DraftWarning>) -> Value {
    let mut obj = Map::new();
    obj.insert("operationId".into(), json!(id));
    if let Some(s) = &op.summary {
        obj.insert("summary".into(), json!(s));
    }
    if let Some(d) = &op.description {
        obj.insert("description".into(), json!(d));
    }
    if !op.tags.is_empty() {
        obj.insert("tags".into(), json!(op.tags));
    }
    let params = parameters(op, warnings);
    if !params.is_empty() {
        obj.insert("parameters".into(), Value::Array(params));
    }
    if let Some(body) = &op.request {
        obj.insert("requestBody".into(), request_body(body));
    }
    let mut responses = Map::new();
    for response in &op.responses {
        responses.insert(response.status.to_string(), response_object(response));
    }
    if responses.is_empty() {
        let target = op.target();
        warnings.push(
            DraftWarning::new(
                "no_responses",
                format!("{target}: no responses were described; a 200 response was added"),
            )
            .for_operation(target),
        );
        responses.insert("200".into(), json!({"description": "OK"}));
    }
    obj.insert("responses".into(), Value::Object(responses));
    Value::Object(obj)
}

/// OpenAPI 3.1 document, the operation id assigned to each input operation
/// (same order), and warnings.
pub fn assemble_openapi(
    title: &str,
    servers: &[String],
    ops: &[DraftOperation],
) -> (Value, Vec<String>, Vec<DraftWarning>) {
    let mut used = HashSet::new();
    let mut ids = Vec::with_capacity(ops.len());
    let mut warnings = Vec::new();
    let mut paths = Map::new();
    for op in ops {
        let id = assign_id(op, &mut used);
        let operation = operation_object(op, &id, &mut warnings);
        let item = paths
            .entry(op.path.clone())
            .or_insert_with(|| Value::Object(Map::new()));
        if let Value::Object(item) = item {
            item.insert(op.method.to_ascii_lowercase(), operation);
        }
        ids.push(id);
    }
    let servers: Vec<Value> = servers.iter().map(|url| json!({"url": url})).collect();
    let doc = json!({
        "openapi": "3.1.0",
        "info": {
            "title": title,
            "version": DRAFT_VERSION,
            "description": DRAFT_DESCRIPTION
        },
        "servers": servers,
        "paths": paths
    });
    (doc, ids, warnings)
}

/// Indexes (ascending) of the operations in `ops`, assembled with `ids`,
/// that `issues` implicate: by a pointer at or under
/// `/paths/{path}/{method}`, or by naming `operation {id}` in the message.
pub fn implicated_operations(
    issues: &[DraftIssue],
    ops: &[DraftOperation],
    ids: &[String],
) -> Vec<usize> {
    ops.iter()
        .zip(ids)
        .enumerate()
        .filter(|(_, (op, id))| {
            let at = format!(
                "/paths/{}/{}",
                escape(&op.path),
                op.method.to_ascii_lowercase()
            );
            issues.iter().any(|issue| {
                issue.pointer == at
                    || issue
                        .pointer
                        .strip_prefix(&at)
                        .is_some_and(|rest| rest.starts_with('/'))
                    || names_operation(&issue.message, id)
            })
        })
        .map(|(i, _)| i)
        .collect()
}

/// Whether `message` contains `operation {id}` as a whole word.
fn names_operation(message: &str, id: &str) -> bool {
    let needle = format!("operation {id}");
    message.match_indices(&needle).any(|(at, _)| {
        !message
            .get(at + needle.len()..)
            .and_then(|rest| rest.chars().next())
            .is_some_and(|c| c.is_alphanumeric() || c == '_' || c == '-' || c == '.')
    })
}

/// The members of an object value with their escaped keys.
fn objects(v: Option<&Value>) -> Vec<(String, &Value)> {
    v.and_then(Value::as_object)
        .map(|m| m.iter().map(|(k, v)| (escape(k), v)).collect())
        .unwrap_or_default()
}

/// Every schema location under `paths` with its JSON pointer.
fn schema_locations(doc: &Value) -> Vec<(String, &Value)> {
    let mut out = Vec::new();
    for (path, item) in objects(doc.get("paths")) {
        for (method, op) in objects(Some(item)) {
            if !op.is_object() {
                continue;
            }
            let at = format!("/paths/{path}/{method}");
            if let Some(params) = op.get("parameters").and_then(Value::as_array) {
                for (i, p) in params.iter().enumerate() {
                    if let Some(s) = p.get("schema") {
                        out.push((format!("{at}/parameters/{i}/schema"), s));
                    }
                }
            }
            for (ct, m) in objects(op.pointer("/requestBody/content")) {
                if let Some(s) = m.get("schema") {
                    out.push((format!("{at}/requestBody/content/{ct}/schema"), s));
                }
            }
            for (status, r) in objects(op.get("responses")) {
                for (ct, m) in objects(r.get("content")) {
                    if let Some(s) = m.get("schema") {
                        out.push((format!("{at}/responses/{status}/content/{ct}/schema"), s));
                    }
                }
            }
        }
    }
    out
}

/// `schema` with `defs` attached as its `$defs` (unless it has its own).
fn with_defs(mut schema: Value, defs: &Map<String, Value>) -> Value {
    if let Value::Object(obj) = &mut schema
        && !defs.is_empty()
        && !obj.contains_key("$defs")
    {
        obj.insert("$defs".into(), Value::Object(defs.clone()));
    }
    schema
}

/// Validates and compiles an (edited) draft document; Ok((pretty JSON
/// source bytes, bundle)).
pub fn compile_draft(doc: &Value) -> Result<(Vec<u8>, Bundle), Vec<DraftIssue>> {
    if !doc.is_object() {
        return Err(vec![DraftIssue::new(
            "/openapi",
            "the draft must be an OpenAPI 3.x document (a JSON object)",
        )]);
    }
    let mut issues = Vec::new();
    if !doc
        .get("openapi")
        .and_then(Value::as_str)
        .is_some_and(|v| v.starts_with("3."))
    {
        issues.push(DraftIssue::new(
            "/openapi",
            "the openapi version must be a 3.x string",
        ));
    }
    if doc.pointer("/info/title").and_then(Value::as_str).is_none() {
        issues.push(DraftIssue::new("/info/title", "missing required field"));
    }

    let components: Map<String, Value> = doc
        .pointer("/components/schemas")
        .and_then(Value::as_object)
        .map(|m| {
            m.iter()
                .map(|(k, v)| (k.clone(), normalize_schema(v, COMPONENTS_PREFIX, false)))
                .collect()
        })
        .unwrap_or_default();
    // Each component is checked on its own (the others stubbed as `true`);
    // one that does not compile is reported once and stubbed elsewhere.
    let stubs: Map<String, Value> = components
        .keys()
        .map(|k| (k.clone(), Value::Bool(true)))
        .collect();
    let mut defs = components.clone();
    for (name, schema) in &components {
        let mut own = stubs.clone();
        own.insert(name.clone(), schema.clone());
        if let Err(e) = jsonschema::validator_for(&with_defs(schema.clone(), &own)) {
            issues.push(DraftIssue::new(
                format!("/components/schemas/{}", escape(name)),
                format!("invalid schema: {e}"),
            ));
            defs.insert(name.clone(), Value::Bool(true));
        }
    }
    for (pointer, schema) in schema_locations(doc) {
        let schema = with_defs(normalize_schema(schema, COMPONENTS_PREFIX, false), &defs);
        if let Err(e) = jsonschema::validator_for(&schema) {
            issues.push(DraftIssue::new(pointer, format!("invalid schema: {e}")));
        }
    }

    let source = match serde_json::to_vec_pretty(doc) {
        Ok(source) => source,
        Err(e) => {
            issues.push(DraftIssue::new("/", e.to_string()));
            return Err(issues);
        }
    };
    match compile(doc, &source) {
        Ok(bundle) if issues.is_empty() => Ok((source, bundle)),
        Ok(_) => Err(issues),
        Err(e) => {
            let issue = match e {
                ImportError::Invalid { pointer, message } => DraftIssue::new(pointer, message),
                other => DraftIssue::new("/", other.to_string()),
            };
            // A problem already reported at the same place is not repeated.
            if !issues.iter().any(|i| i.pointer == issue.pointer) {
                issues.push(issue);
            }
            Err(issues)
        }
    }
}

/// Meta after an edit: removed ids dropped; new or changed operations get
/// confidence 1.0, edited = true; meta.edited = true.
pub fn refresh_meta(meta: &DraftMeta, old: &Bundle, new: &Bundle) -> DraftMeta {
    let old_ops: BTreeMap<&str, &Operation> =
        old.operations.iter().map(|o| (o.id.as_str(), o)).collect();
    let mut operations = BTreeMap::new();
    for op in &new.operations {
        let previous = meta.operations.get(&op.id);
        let entry = match (old_ops.get(op.id.as_str()), previous) {
            (Some(old_op), Some(previous)) if *old_op == op => previous.clone(),
            (_, previous) => OperationMeta {
                confidence: 1.0,
                provenance: previous.map(|p| p.provenance.clone()).unwrap_or_default(),
                edited: true,
            },
        };
        operations.insert(op.id.clone(), entry);
    }
    DraftMeta {
        operations,
        edited: true,
        ..meta.clone()
    }
}

/// `"GET /pets/{petId}"` with every `{name}` replaced by `{}`.
fn diff_key(op: &Operation) -> String {
    let target = op.target();
    let mut out = String::with_capacity(target.len());
    let mut in_param = false;
    for c in target.chars() {
        match c {
            '{' => {
                in_param = true;
                out.push('{');
            }
            '}' if in_param => {
                in_param = false;
                out.push('}');
            }
            _ if in_param => {}
            _ => out.push(c),
        }
    }
    out
}

/// The operation without what does not count as a change: its id and the
/// names of its path parameters in the binding.
fn comparable(op: &Operation) -> Operation {
    let mut op = op.clone();
    op.id = String::new();
    if let Binding::Http { path, .. } = &mut op.binding {
        *path = diff_key_path(path);
    }
    op
}

fn diff_key_path(path: &str) -> String {
    path.split('/')
        .map(|s| {
            if s.starts_with('{') && s.ends_with('}') {
                "{}"
            } else {
                s
            }
        })
        .collect::<Vec<_>>()
        .join("/")
}

/// Keyed by Operation::target() with "{name}" normalized to "{}"; draft
/// targets reported; sorted.
pub fn diff_bundles(active: &Bundle, draft: &Bundle) -> BundleDiff {
    let index = |b: &Bundle| -> BTreeMap<String, Operation> {
        let mut map = BTreeMap::new();
        for op in &b.operations {
            map.entry(diff_key(op)).or_insert_with(|| op.clone());
        }
        map
    };
    let active_ops = index(active);
    let draft_ops = index(draft);
    let mut diff = BundleDiff::default();
    for (key, op) in &draft_ops {
        match active_ops.get(key) {
            None => diff.added.push(op.target()),
            Some(old) if comparable(old) != comparable(op) => diff.changed.push(op.target()),
            Some(_) => {}
        }
    }
    for (key, op) in &active_ops {
        if !draft_ops.contains_key(key) {
            diff.removed.push(op.target());
        }
    }
    diff.added.sort();
    diff.removed.sort();
    diff.changed.sort();
    diff
}
