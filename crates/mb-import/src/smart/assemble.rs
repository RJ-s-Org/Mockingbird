//! OpenAPI 3.1 assembly of draft operations, validation and compilation of
//! (edited) draft documents, and the review helpers that compare drafts.

use std::collections::{BTreeMap, HashSet};

use mb_mcm::{Binding, Bundle, Operation};
use serde::Serialize;
use serde_json::{Map, Value, json};

use super::infer::{infer_scalar, infer_schema};
use super::model::{
    DraftBody, DraftMeta, DraftOperation, DraftParam, DraftResponse, DraftWarning, OperationMeta,
    ParamLocation,
};
use crate::ImportError;
